import {
  CLINIC_AREA,
  CLINIC_CITY,
  CLINIC_EMAIL,
  CLINIC_FOUNDED_YEAR,
  CLINIC_GEO,
  CLINIC_MAPS_URL,
  CLINIC_NAME,
  CLINIC_SHORT_NAME,
  CLINIC_STREET,
  FOUNDER,
  parseHours,
  REGULAR_PHONE,
  SOCIAL_LINKS,
  WORKING_HOURS,
} from "./constants";
import routesJson from "./routes.json";

/** Production origin, set once in routes.json (also used by sitemap/robots). */
export const SITE_URL = routesJson.siteUrl;
export const SITE_NAME = CLINIC_NAME;
/**
 * Appended to every <title>. The short brand keeps titles near the ~60
 * characters Google shows; the full name is still in og:site_name and the
 * WebSite schema.
 */
export const TITLE_SUFFIX = CLINIC_SHORT_NAME;
/** Generated by script/optimize-images.mjs (1200×630). */
export const DEFAULT_OG_IMAGE = "/og-image.jpg";
export const DEFAULT_OG_IMAGE_SIZE = { width: 1200, height: 630 } as const;
/** Wordmark generated from the logo; swap when the English logo arrives. */
export const LOGO_URL = `${SITE_URL}/logo.png`;

const CLINIC_ID = `${SITE_URL}/#clinic`;
const WEBSITE_ID = `${SITE_URL}/#website`;

function openingHoursSpecification() {
  return WORKING_HOURS
    .map((wh) => {
      const parsed = parseHours(wh.hours);
      if (!parsed) return null;
      return {
        "@type": "OpeningHoursSpecification",
        dayOfWeek: wh.day,
        opens: parsed.opens,
        closes: parsed.closes,
      };
    })
    .filter(Boolean);
}

// UAE addresses have no Western postal code — the field is intentionally
// omitted rather than shipped with a bogus value.
function postalAddress() {
  return {
    "@type": "PostalAddress",
    streetAddress: CLINIC_STREET,
    addressLocality: CLINIC_AREA,
    addressRegion: CLINIC_CITY,
    addressCountry: "AE",
  };
}

function founderPerson() {
  return {
    "@type": "Person",
    name: FOUNDER.name,
    honorificSuffix: FOUNDER.credentials,
    jobTitle: FOUNDER.title,
    worksFor: { "@id": CLINIC_ID },
  };
}

const AREA_SERVED = { "@type": "City", name: CLINIC_CITY };

/**
 * Compact reference to the clinic for pages other than Home. Google resolves
 * `@id` only within one page, so each page that points at the clinic carries
 * enough of it (name, address, phone) to stand alone.
 */
export function clinicRef() {
  return {
    "@type": "Dentist",
    "@id": CLINIC_ID,
    name: SITE_NAME,
    url: SITE_URL,
    telephone: REGULAR_PHONE,
    address: postalAddress(),
  };
}

/**
 * The clinic as one entity: Dentist is a LocalBusiness and an Organization,
 * so logo, founder and contact details live on the same node instead of a
 * second Organization that Google could read as a different company.
 */
export function jsonLdLocalBusiness() {
  return {
    "@context": "https://schema.org",
    "@type": "Dentist",
    "@id": CLINIC_ID,
    name: SITE_NAME,
    alternateName: CLINIC_SHORT_NAME,
    // No real clinic photo yet (owner is sending interior shots) — the logo
    // stands in rather than a stock image presented as the premises.
    image: LOGO_URL,
    logo: LOGO_URL,
    description:
      "Dental center in Dubai JLT specializing in complex cases: emergency care, Hollywood smiles, full-mouth implant rehabilitation, no-prep ceramic veneers, crowns, orthodontics and private at-home dental visits.",
    address: postalAddress(),
    geo: { "@type": "GeoCoordinates", ...CLINIC_GEO },
    hasMap: CLINIC_MAPS_URL,
    telephone: REGULAR_PHONE,
    email: CLINIC_EMAIL,
    url: SITE_URL,
    areaServed: AREA_SERVED,
    medicalSpecialty: "https://schema.org/Dentistry",
    founder: founderPerson(),
    foundingDate: CLINIC_FOUNDED_YEAR,
    sameAs: Object.values(SOCIAL_LINKS),
    contactPoint: {
      "@type": "ContactPoint",
      contactType: "customer service",
      telephone: REGULAR_PHONE,
      email: CLINIC_EMAIL,
      areaServed: "AE",
    },
    openingHoursSpecification: openingHoursSpecification(),
    // No aggregateRating: the 107 reviews live on Google, not on this site.
    // Google's review-snippet rules forbid marking up ratings collected
    // elsewhere, and a business rating itself never earns stars anyway. The
    // rating stays visible on the page (Footer, GoogleRatingBanner).
  };
}

/** Site-level schema; gives Google the site name shown above the result. */
export function jsonLdWebSite() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": WEBSITE_ID,
    name: SITE_NAME,
    alternateName: CLINIC_SHORT_NAME,
    url: `${SITE_URL}/`,
    inLanguage: "en",
    publisher: { "@id": CLINIC_ID },
  };
}

/**
 * Schema for a single treatment page. A Service (not MedicalProcedure, which
 * has no `provider` / `areaServed`) offered by the clinic in Dubai.
 */
export function jsonLdService(opts: {
  name: string;
  description: string;
  path: string;
  serviceType?: string;
}) {
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    name: opts.name,
    description: opts.description,
    url: `${SITE_URL}${opts.path}`,
    serviceType: opts.serviceType ?? opts.name,
    category: "Dentistry",
    provider: clinicRef(),
    areaServed: AREA_SERVED,
  };
}

/** Schema for a blog article. Authored and published by the clinic. */
export function jsonLdArticle(opts: {
  headline: string;
  description: string;
  path: string;
  datePublished: string;
  dateModified?: string;
  image?: string;
}) {
  const url = `${SITE_URL}${opts.path}`;
  return {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    headline: opts.headline,
    description: opts.description,
    url,
    mainEntityOfPage: url,
    datePublished: opts.datePublished,
    dateModified: opts.dateModified ?? opts.datePublished,
    image: opts.image ?? `${SITE_URL}${DEFAULT_OG_IMAGE}`,
    inLanguage: "en",
    // The clinic itself (same @id as the Dentist entity), not an anonymous
    // Organization that Google could read as a different publisher.
    author: clinicRef(),
    publisher: { ...clinicRef(), logo: { "@type": "ImageObject", url: LOGO_URL } },
  };
}

export function jsonLdFAQPage(
  faqs: ReadonlyArray<{ question: string; answer: string }>
) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((f) => ({
      "@type": "Question",
      name: f.question,
      acceptedAnswer: { "@type": "Answer", text: f.answer },
    })),
  };
}

export function jsonLdBreadcrumb(
  items: Array<{ name: string; path: string }>
) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      item: `${SITE_URL}${item.path}`,
    })),
  };
}
